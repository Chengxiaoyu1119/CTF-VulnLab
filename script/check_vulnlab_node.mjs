import assert from 'node:assert/strict'
import { readFile, stat } from 'node:fs/promises'
import { resolve } from 'node:path'

const root = resolve(import.meta.dirname, '..')
const read = path => readFile(resolve(root, path), 'utf8')
const exists = async path => (await stat(resolve(root, path)).catch(() => null))?.isFile() === true

const packageJson = JSON.parse(await read('src/VulnLab/package.json'))
const server = await read('src/VulnLab/server.ts')
const providers = await read('src/VulnLab/providers.ts')
const importer = await read('src/VulnLab/importer.ts')
const importers = await read('src/VulnLab/importers.ts')
const runtimeStatus = await read('src/VulnLab/runtime-status.ts')
const seed = await read('src/VulnLab/seed.ts')
const web = await read('src/VulnLab/public/app.js')
const css = await read('src/VulnLab/public/styles.css')
const covers = await read('src/VulnLab/public/covers/README.md')
const deploymentReadme = await read('operations/deploy/vulnlab/native/README.zh-CN.md')
const deploymentEnv = await read('operations/deploy/vulnlab/native/.env.example')

assert.equal(packageJson.name, 'vulnlab')
assert.equal(packageJson.type, 'module')
assert.ok(packageJson.dependencies.fastify)
assert.ok(packageJson.dependencies['better-sqlite3'])
assert.match(packageJson.scripts.test, /test_vulnlab_provider\.mjs/)
assert.doesNotMatch(packageJson.scripts.test, /vm_download|vulnhub/i)

assert.match(server, /\/api\/labs\/:id\/install/)
assert.match(server, /\/api\/labs\/:id\/instances/)
assert.match(server, /\/lab-runtime\//)
assert.match(server, /native-php.*native-node.*native-java.*native-python/)
assert.doesNotMatch(server, /环境页显示待配置状态/)
for (const pattern of [/importVulnHubCatalog/, /VmDownload/, /qemu-vm/, /VULNLAB_QEMU_BIN/, /\/api\/vm-downloads/, /\/catalog\/entries/]) assert.doesNotMatch(server, pattern)

assert.match(importers, /github-git/)
assert.match(importers, /gitlab-git/)
assert.match(importer, /archiveSha256/)
assert.match(importer, /assertPortablePaths/)
assert.match(providers, /class NativePhpProvider/)
assert.match(providers, /class NativeProcessProvider/)
assert.match(providers, /configureXvwa/)
for (const pattern of [/QemuVmProvider/, /qemu-vm/, /extractOva/, /QEMU_OVA_PATH_INVALID/]) assert.doesNotMatch(providers, pattern)

assert.match(runtimeStatus, /php-pdo-mysql/)
assert.match(runtimeStatus, /xvwa/)
assert.doesNotMatch(runtimeStatus, /qemu/i)
assert.match(seed, /slug: 'xvwa'/)
assert.match(seed, /title: 'XVWA'/)
assert.match(seed, /sourceRef: 's4n7h0\/xvwa@fb30fa517d288e618b521d252f61107ef6a24797'/)
assert.doesNotMatch(seed, /VulnHub Machines|vulnhub/i)

assert.match(web, /xvwa: '\/covers\/xvwa\.png'/)
assert.match(web, /mutillidae: '\/covers\/mutillidae\.svg'/)
assert.match(web, /pygoat: '\/covers\/pygoat\.svg'/)
assert.doesNotMatch(web, /runtimePanel\(|runtime-panel/)
assert.match(web, /data-action="start-instance"/)
assert.match(web, /启动环境/)
assert.match(web, /打开页面/)
assert.doesNotMatch(web, /安装靶场|待安装|等待安装|安装中|启动条件|待配置/)
assert.doesNotMatch(web, /data-action="install-lab"/)
for (const pattern of [/runtimeRequirementsDialog/, /runtimeDialogLabId/, /open-runtime-dialog/, /close-runtime-dialog/, /prepare-runtime/]) assert.doesNotMatch(web, pattern)
for (const pattern of [/catalog/i, /vulnhub/i, /QEMU/i, /vmDownloads/, /选择启动环境/, /下载镜像/]) assert.doesNotMatch(web, pattern)
for (const pattern of [/catalog-/i, /data-action="view-catalog"/, /data-action="start-vm-instance"/]) assert.doesNotMatch(css, pattern)
assert.match(css, /grid-template-columns:\s*repeat\(3,/)
assert.match(css, /grid-template-columns:\s*repeat\(2,/)
assert.match(css, /prefers-reduced-motion/)
assert.match(covers, /`xvwa\.png`/)
assert.match(covers, /`mutillidae\.svg`/)
assert.match(covers, /`pygoat\.svg`/)
assert.ok(await exists('src/VulnLab/public/covers/xvwa.png'))
assert.ok(await exists('src/VulnLab/public/covers/mutillidae.svg'))
assert.ok(await exists('src/VulnLab/public/covers/pygoat.svg'))
assert.equal(await exists('src/VulnLab/public/covers/vulnhub.png'), false)

assert.match(deploymentReadme, /PHP、Node\.js、Java、Python 四类 Provider/)
assert.doesNotMatch(deploymentReadme, /QEMU|VulnHub/i)
assert.doesNotMatch(deploymentReadme, /查看启动条件|环境页面/)
assert.doesNotMatch(deploymentEnv, /QEMU|VulnHub|OVA/i)

console.log('VulnLab Node structure check passed: XVWA native runtime, four Providers, unified install/start flow and current docs.')
